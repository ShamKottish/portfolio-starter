// Index-wise merge: arrays line up by position, objects by key.
function merge(base, over) {
  if (over === undefined) return base;
  if (Array.isArray(base) && Array.isArray(over)) {
    return base.map((item, i) => merge(item, over[i])).concat(over.slice(base.length));
  }
  if (base && over && typeof base === "object" && typeof over === "object" && !Array.isArray(base)) {
    const out = { ...base };
    for (const key of Object.keys(over)) out[key] = merge(base[key], over[key]);
    return out;
  }
  return over;
}

